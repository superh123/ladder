/**
 * Precompute the daily-pairs bank (run once, not at runtime).
 *
 * Samples start/end pairs from the common-word list, BFSes them on the
 * GUESS graph, and keeps only pairs with par 4-6 AND at least 2 distinct
 * shortest paths — so every daily puzzle is solvable, fair, and never has
 * a single forced line.
 *
 * Run: `node scripts/precompute-pairs.mjs`
 * Output: `src/lib/daily-pairs.ts` (90 pairs).
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

function loadWords(file) {
  const src = readFileSync(join(root, 'src/lib', file), 'utf8')
  return [...src.matchAll(/'([a-z]{4})'/g)].map((m) => m[1])
}

const COMMON = loadWords('words-common.ts')
const GUESS = loadWords('words-guess.ts')
console.log(`common=${COMMON.length} guess=${GUESS.length}`)

const buckets = new Map()
for (const w of GUESS) {
  for (let i = 0; i < 4; i++) {
    const key = w.slice(0, i) + '_' + w.slice(i + 1)
    if (!buckets.has(key)) buckets.set(key, [])
    buckets.get(key).push(w)
  }
}
function neighbors(w) {
  const out = new Set()
  for (let i = 0; i < 4; i++) {
    const key = w.slice(0, i) + '_' + w.slice(i + 1)
    for (const v of buckets.get(key) ?? []) if (v !== w) out.add(v)
  }
  return [...out]
}

// BFS with distinct-shortest-path counting (capped at 3).
function bfs(start, end) {
  if (start === end) return { dist: 0, count: 1 }
  const dist = new Map([[start, 0]])
  const count = new Map([[start, 1]])
  const q = [start]
  let head = 0
  while (head < q.length) {
    const u = q[head++]
    const du = dist.get(u)
    const endDist = dist.get(end)
    if (endDist !== undefined && du > endDist) break
    for (const v of neighbors(u)) {
      const dv = dist.get(v)
      if (dv === undefined) {
        dist.set(v, du + 1)
        count.set(v, count.get(u))
        q.push(v)
      } else if (dv === du + 1) {
        count.set(v, Math.min(3, (count.get(v) ?? 0) + (count.get(u) ?? 1)))
      }
    }
  }
  const d = dist.get(end)
  return d === undefined ? { dist: -1, count: 0 } : { dist: d, count: count.get(end) ?? 1 }
}

// Deterministic PRNG (mulberry32) so the bank is reproducible.
function mulberry32(seed) {
  return function () {
    seed |= 0
    seed = (seed + 0x6d2b79f5) | 0
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed)
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

const rand = mulberry32(20261122)
const TARGET = 90
const pairs = []
const seenPair = new Set()
const startUse = new Map()
let tries = 0
while (pairs.length < TARGET && tries < 20000) {
  tries++
  const a = COMMON[Math.floor(rand() * COMMON.length)]
  const b = COMMON[Math.floor(rand() * COMMON.length)]
  if (a === b) continue
  const key = [a, b].sort().join('-')
  if (seenPair.has(key)) continue
  if ((startUse.get(a) ?? 0) >= 2 || (startUse.get(b) ?? 0) >= 2) continue
  const { dist, count } = bfs(a, b)
  if (dist >= 4 && dist <= 6 && count >= 2) {
    pairs.push([a, b, dist, count])
    seenPair.add(key)
    startUse.set(a, (startUse.get(a) ?? 0) + 1)
    startUse.set(b, (startUse.get(b) ?? 0) + 1)
  }
}
console.log(`tries=${tries} kept=${pairs.length}`)
for (const [a, b, par, count] of pairs) {
  console.log(`${a} -> ${b} par ${par} paths>=${count}`)
}
if (pairs.length < TARGET) {
  console.error(`only ${pairs.length} pairs — refusing to write a short bank`)
  process.exit(1)
}
const body = pairs.map(([a, b]) => `  ['${a}', '${b}'],`).join('\n')
const out = `/**
 * Precomputed daily pairs — generated by scripts/precompute-pairs.mjs.
 * Every pair is solvable on the guess graph with par 4-6 and at least 2
 * distinct shortest paths. Do not hand-edit: re-run the script.
 * Ladder #N (N = days since 2026-11-22 UTC + 1) uses pair (N-1) % ${pairs.length}.
 */
export const DAILY_PAIRS: readonly (readonly [string, string])[] = [
${body},
] as const
`
writeFileSync(join(root, 'src/lib/daily-pairs.ts'), out)
console.log('wrote src/lib/daily-pairs.ts')
