// Regenerates src/lib/words-legit.ts (the presentation set for hints and
// the optimal-path reveal). Downloads the Hunspell en_US dictionary from
// wooorm/dictionaries and keeps guess-list words that are a base form or a
// regular inflection (-s, -ed, -er, -est, -ly) of one, plus every
// common-list word. Run with: node scripts/build-legit-list.mjs
import { writeFileSync } from 'node:fs'

const DIC_URL =
  'https://raw.githubusercontent.com/wooorm/dictionaries/main/dictionaries/en/index.dic'

const guessText = await (await fetch(new URL('../src/lib/words-guess.ts', import.meta.url))).text()
const guess = [...guessText.matchAll(/'([a-z]{4})'/g)].map((m) => m[1])
const common = JSON.parse(
  await (await fetch(new URL('../../words-4letter.json', import.meta.url))).text(),
)
const dicText = await (await fetch(DIC_URL)).text()
const base = new Set()
for (const line of dicText.split('\n')) {
  const w = line.trim().split('/')[0]
  if (/^[a-z]+$/.test(w)) base.add(w)
}
const legit = (w) =>
  base.has(w) ||
  (w.endsWith('s') && base.has(w.slice(0, -1))) ||
  (w.endsWith('ed') && (base.has(w.slice(0, -2)) || base.has(w.slice(0, -1)))) ||
  (w.endsWith('er') && base.has(w.slice(0, -2))) ||
  (w.endsWith('est') && base.has(w.slice(0, -3))) ||
  (w.endsWith('ly') && base.has(w.slice(0, -2)))
const set = [...new Set([...guess.filter(legit), ...common])].sort()
const header = `// Words a hint or optimal-path reveal is allowed to route through.
// Derived from the guess list by keeping words that are a base form in
// the Hunspell en_US dictionary (wooorm/dictionaries) or a regular
// inflection of one (-s, -ed, -er, -est, -ly), plus every common-list
// word. This is a *presentation* set only: validation still accepts
// any guess-list word, so players are never blocked from typing a
// real-but-obscure word. Generated by scripts/build-legit-list.mjs.
export const WORDS_LEGIT = [
`
const body = []
for (let i = 0; i < set.length; i += 8) {
  body.push('  ' + set.slice(i, i + 8).map((w) => `'${w}',`).join(' '))
}
writeFileSync(new URL('../src/lib/words-legit.ts', import.meta.url), header + body.join('\n') + '\n] as const\n')
console.log(`legit=${set.length} wrote src/lib/words-legit.ts`)
