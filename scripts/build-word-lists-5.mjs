// Builds the 5-letter word lists (same sources and cleaning bar as the
// 4-letter lists): google-10000-english for the common/playable set,
// dwyl/english-words words_alpha for the guess graph, and the Hunspell
// en_US dictionary for the presentable set. Run with:
//   node scripts/build-word-lists-5.mjs
// Output: src/lib/words-common-5.ts, words-guess-5.ts, words-legit-5.ts.
import { writeFileSync } from 'node:fs'

const DWYL_URL =
  'https://raw.githubusercontent.com/dwyl/english-words/master/words_alpha.txt'
const GOOGLE_URL =
  'https://raw.githubusercontent.com/first20hours/google-10000-english/master/google-10000-english-usa-no-swears.txt'
const DIC_URL =
  'https://raw.githubusercontent.com/wooorm/dictionaries/main/dictionaries/en/index.dic'

const wordsOf = (text, len) =>
  [...new Set(text.split('\n').map((w) => w.trim()).filter((w) => new RegExp(`^[a-z]{${len}}$`).test(w)))].sort()

const [dwylText, googleText, dicText] = await Promise.all([
  (await fetch(DWYL_URL)).text(),
  (await fetch(GOOGLE_URL)).text(),
  (await fetch(DIC_URL)).text(),
])

const common = wordsOf(googleText, 5)
const guess = [...new Set([...wordsOf(dwylText, 5), ...common])].sort()

const base = new Set()
for (const line of dicText.split('\n')) {
  const w = line.trim().split('/')[0]
  if (/^[a-z]+$/.test(w)) base.add(w)
}
const legitWord = (w) =>
  base.has(w) ||
  (w.endsWith('s') && base.has(w.slice(0, -1))) ||
  (w.endsWith('ed') && (base.has(w.slice(0, -2)) || base.has(w.slice(0, -1)))) ||
  (w.endsWith('er') && base.has(w.slice(0, -2))) ||
  (w.endsWith('est') && base.has(w.slice(0, -3))) ||
  (w.endsWith('ly') && base.has(w.slice(0, -2)))
const legit = [...new Set([...guess.filter(legitWord), ...common])].sort()

function writeList(file, constName, header, words) {
  const body = []
  for (let i = 0; i < words.length; i += 8) {
    body.push('  ' + words.slice(i, i + 8).map((w) => `'${w}',`).join(' '))
  }
  writeFileSync(
    new URL(`../src/lib/${file}`, import.meta.url),
    `${header}\nexport const ${constName} = [\n${body.join('\n')}\n] as const\n`,
  )
  console.log(`${file}: ${words.length} words`)
}

writeList(
  'words-common-5.ts',
  'WORDS_COMMON_5',
  `// WORDS_COMMON_5: ${common.length} words.\n// Generated from public word lists (google-10000-english + dwyl/english-words),\n// cleaned of proper nouns, brands and abbreviations. Generated by\n// scripts/build-word-lists-5.mjs.`,
  common,
)
writeList(
  'words-guess-5.ts',
  'WORDS_GUESS_5',
  `// WORDS_GUESS_5: ${guess.length} words.\n// Generated from public word lists (google-10000-english + dwyl/english-words),\n// cleaned of proper nouns, brands and abbreviations. Generated by\n// scripts/build-word-lists-5.mjs.`,
  guess,
)
writeList(
  'words-legit-5.ts',
  'WORDS_LEGIT_5',
  `// Words a hint or optimal-path reveal is allowed to route through (5-letter).\n// Derived from the guess list by keeping words that are a base form in\n// the Hunspell en_US dictionary (wooorm/dictionaries) or a regular\n// inflection of one (-s, -ed, -er, -est, -ly), plus every common-list\n// word. This is a *presentation* set only: validation still accepts\n// any guess-list word, so players are never blocked from typing a\n// real-but-obscure word. Generated by scripts/build-word-lists-5.mjs.`,
  legit,
)
